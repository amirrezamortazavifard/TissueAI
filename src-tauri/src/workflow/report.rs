use crate::workflow::recorder::WorkflowPipeline;
use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct PathologyReportInput {
    pub slide_name: String,
    pub specimen_id: String,
    pub pixel_size_um: f64,
    pub total_nuclei_detected: usize,
    pub mean_nuclear_area_um2: f64,
    pub mean_circularity: f64,
    pub positive_fraction: f64,
}

pub struct ResearchReportGenerator;

impl ResearchReportGenerator {
    /// Generates structured scientific Markdown report for pathology publication & documentation (options.md WF-06)
    pub fn generate_markdown(input: &PathologyReportInput, pipeline: &WorkflowPipeline) -> String {
        let mut md = String::new();
        md.push_str("# TissueAI Quantitative Pathology & Morphometric Report\n\n");
        md.push_str(&format!("- **Specimen ID:** {}\n", input.specimen_id));
        md.push_str(&format!("- **Slide Name:** {}\n", input.slide_name));
        md.push_str(&format!("- **Spatial Calibration:** {:.4} µm/pixel\n", input.pixel_size_um));
        md.push_str(&format!("- **Generated Date:** {}\n\n", chrono::Utc::now().to_rfc3339()));

        md.push_str("## 1. Quantitative Morphometric Summary\n\n");
        md.push_str("| Metric | Value | Unit |\n");
        md.push_str("| :--- | :--- | :--- |\n");
        md.push_str(&format!("| Total Objects / Nuclei Detected | {} | count |\n", input.total_nuclei_detected));
        md.push_str(&format!("| Mean Nuclear Area | {:.2} | µm² |\n", input.mean_nuclear_area_um2));
        md.push_str(&format!("| Mean Circularity (4π·Area/Perimeter²) | {:.3} | score (0-1) |\n", input.mean_circularity));
        md.push_str(&format!("| Positive Biomarker Fraction | {:.1}% | percentage |\n\n", input.positive_fraction * 100.0));

        md.push_str("## 2. Scientific Reproducibility & Audit Trail (Provenance)\n\n");
        md.push_str(&format!("Pipeline ID: `{}`\n\n", pipeline.id));
        md.push_str("| Step # | Command | Execution Time (ms) | Status |\n");
        md.push_str("| :--- | :--- | :--- | :--- |\n");

        for (idx, step) in pipeline.steps.iter().enumerate() {
            let status = if step.success { "Success" } else { "Failed" };
            md.push_str(&format!(
                "| {} | `{}` | {:.2} ms | {} |\n",
                idx + 1,
                step.command,
                step.execution_ms,
                status
            ));
        }

        md.push_str("\n---\n*Report automatically generated by TissueAI (Scientific Image Computing Engine)*\n");
        md
    }
}
