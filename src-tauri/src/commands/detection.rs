use std::sync::Mutex;
use std::path::PathBuf;

use crate::tools::detection::bounding_box::{BoundingBox, ImageDetectionResult, DetectionInfo};

pub struct DetectionState {
    #[allow(dead_code)]
    pub cached_model_path: Mutex<Option<String>>,
    pub last_detection_results: Mutex<Vec<DetectionInfo>>,
}

impl DetectionState {
    pub fn new() -> Self {
        DetectionState {
            cached_model_path: Mutex::new(None),
            last_detection_results: Mutex::new(Vec::new()),
        }
    }
}

fn get_models_dir() -> PathBuf {
    if let Ok(home) = std::env::var("USERPROFILE") {
        let app_data = PathBuf::from(home)
            .join("AppData")
            .join("Roaming")
            .join("TissueAI")
            .join("models")
            .join("detect");
        let _ = std::fs::create_dir_all(&app_data);
        return app_data;
    }
    PathBuf::from("models/detect")
}

#[tauri::command]
pub fn get_models_directory() -> Result<String, String> {
    Ok(get_models_dir().to_string_lossy().to_string())
}

#[tauri::command]
pub fn load_detection_model(model_path: String) -> Result<String, String> {
    let model = crate::tools::detection::yolo_model::YoloModel::from_file(&model_path)
        .map_err(|e| format!("Failed to load model: {}", e))?;

    let class_count = model.class_names.len();
    let class_names = model.class_names.clone();

    Ok(format!(
        "Model loaded with {} classes: {}",
        class_count,
        class_names.join(", ")
    ))
}

#[tauri::command]
pub fn run_detection(
    image_path: String,
    model_path: String,
    confidence_threshold: f32,
    nms_threshold: f32,
    state: tauri::State<'_, DetectionState>,
) -> Result<ImageDetectionResult, String> {
    let mut model = crate::tools::detection::yolo_model::YoloModel::from_file(&model_path)
        .map_err(|e| format!("Failed to create model: {}", e))?;

    let result = model.detect_objects(&image_path, confidence_threshold, nms_threshold)
        .map_err(|e| format!("Detection failed: {}", e))?;

    let mut stored = state.last_detection_results.lock().unwrap();
    *stored = result
        .detections
        .iter()
        .enumerate()
        .map(|(idx, b)| DetectionInfo {
            index: idx,
            label: b.class_name.clone(),
            confidence: b.confidence,
            original_box: b.clone(),
        })
        .collect();

    Ok(result)
}

fn box_color(class_id: i32) -> [u8; 3] {
    let palette: [[u8; 3]; 10] = [
        [255, 80, 80],
        [80, 200, 80],
        [80, 120, 255],
        [255, 200, 50],
        [220, 80, 220],
        [50, 200, 200],
        [200, 100, 50],
        [50, 180, 100],
        [100, 80, 200],
        [200, 200, 80],
    ];
    palette[((class_id % 10 + 10) % 10) as usize]
}

#[tauri::command]
pub fn draw_bounding_boxes(
    image_path: String,
    boxes: Vec<BoundingBox>,
) -> Result<String, String> {
    let img = image::open(&image_path).map_err(|e| format!("Failed to open image: {}", e))?;
    let mut rgb_img = img.to_rgb8();

    let img_width = rgb_img.width() as f32;
    let img_height = rgb_img.height() as f32;

    let scale = 640.0_f32 / img_width.max(img_height);
    let scaled_w = img_width * scale;
    let scaled_h = img_height * scale;
    let offset_x = (640.0 - scaled_w) / 2.0;
    let offset_y = (640.0 - scaled_h) / 2.0;

    let line_thickness = ((img_width / 400.0) as u32).max(2);

    for box_item in &boxes {
        let color = box_color(box_item.class_id);

        let model_left = box_item.x - box_item.width / 2.0;
        let model_top = box_item.y - box_item.height / 2.0;

        let orig_left = ((model_left - offset_x) / scale).max(0.0);
        let orig_top = ((model_top - offset_y) / scale).max(0.0);
        let orig_right = ((model_left + box_item.width - offset_x) / scale).min(img_width);
        let orig_bottom = ((model_top + box_item.height - offset_y) / scale).min(img_height);

        let left = orig_left as i32;
        let top = orig_top as i32;
        let right = orig_right as i32;
        let bottom = orig_bottom as i32;

        let w = (right - left).max(1) as u32;
        let h = (bottom - top).max(1) as u32;

        for x in left..(left + w as i32) {
            for t in 0..line_thickness as i32 {
                let py = top + t;
                if py >= 0 && py < img_height as i32 {
                    rgb_img.put_pixel(x as u32, py as u32, image::Rgb(color));
                }
                let py = top + h as i32 - 1 - t;
                if py >= 0 && py < img_height as i32 {
                    rgb_img.put_pixel(x as u32, py as u32, image::Rgb(color));
                }
            }
        }
        for y in top..(top + h as i32) {
            for t in 0..line_thickness as i32 {
                let px = left + t;
                if px >= 0 && px < img_width as i32 {
                    rgb_img.put_pixel(px as u32, y as u32, image::Rgb(color));
                }
                let px = left + w as i32 - 1 - t;
                if px >= 0 && px < img_width as i32 {
                    rgb_img.put_pixel(px as u32, y as u32, image::Rgb(color));
                }
            }
        }

        let label = format!("{} {:.0}%", box_item.class_name, box_item.confidence * 100.0);
        let label_w = label.len() as i32 * 8;
        let label_h = 16;
        let label_x = left;
        let label_y = (top - label_h - 2).max(0);

        for lx in label_x..(label_x + label_w).min(img_width as i32) {
            for ly in label_y..(label_y + label_h).min(img_height as i32) {
                rgb_img.put_pixel(lx as u32, ly as u32, image::Rgb(color));
            }
        }

        let mut draw_x = label_x + 2;
        for ch in label.chars() {
            if draw_x + 6 > img_width as i32 {
                break;
            }
            let ascii = ch as u8;
            if ascii >= 32 && ascii <= 126 {
                let glyph = FONT_8X8[(ascii - 32) as usize];
                for gy in 0..8 {
                    for gx in 0..8 {
                        if glyph[gy] & (1 << gx) != 0 {
                            let px = draw_x + gx;
                            let py = label_y + gy as i32;
                            if px >= 0 && px < img_width as i32 && py >= 0 && py < img_height as i32 {
                                rgb_img.put_pixel(px as u32, py as u32, image::Rgb([255, 255, 255]));
                            }
                        }
                    }
                }
            }
            draw_x += 8;
        }
    }

    let mut buffer: Vec<u8> = Vec::new();
    let encoder = image::codecs::png::PngEncoder::new(&mut buffer);
    image::ImageEncoder::write_image(
        encoder,
        rgb_img.as_raw(),
        rgb_img.width(),
        rgb_img.height(),
        image::ExtendedColorType::Rgb8,
    )
    .map_err(|e| format!("Failed to encode PNG: {}", e))?;

    use base64::Engine;
    let base64_string = base64::engine::general_purpose::STANDARD.encode(&buffer);

    Ok(format!("data:image/png;base64,{}", base64_string))
}

#[tauri::command]
pub fn get_detection_results(state: tauri::State<'_, DetectionState>) -> Result<Vec<DetectionInfo>, String> {
    Ok(state.last_detection_results.lock().unwrap().clone())
}

#[tauri::command]
pub fn export_detection_csv(
    image_path: String,
    detections: Vec<BoundingBox>,
    processing_time_ms: f64,
) -> Result<String, String> {
    let mut csv = String::from("ImageName,TotalDetectionsInImage,DetectionTime(ms),DetectionID,ClassName,Confidence,Box_X,Box_Y,Box_Width,Box_Height\n");

    for (i, det) in detections.iter().enumerate() {
        csv.push_str(&format!(
            "{},{},{},{},{},{:.4},{:.2},{:.2},{:.2},{:.2}\n",
            PathBuf::from(&image_path)
                .file_name()
                .unwrap_or_default()
                .to_string_lossy(),
            detections.len(),
            processing_time_ms,
            i + 1,
            det.class_name,
            det.confidence,
            det.x,
            det.y,
            det.width,
            det.height
        ));
    }

    Ok(csv)
}

#[tauri::command]
pub fn list_models_in_directory(directory: String) -> Result<Vec<String>, String> {
    let mut models = Vec::new();

    let dir = PathBuf::from(&directory);
    if !dir.exists() {
        let _ = std::fs::create_dir_all(&dir);
        return Ok(models);
    }

    if let Ok(entries) = std::fs::read_dir(&dir) {
        for entry in entries.flatten() {
            let path = entry.path();
            if path.is_file() {
                if let Some(ext) = path.extension() {
                    if ext == "tissueaimodel" || ext == "onnx" {
                        models.push(path.file_name().unwrap_or_default().to_string_lossy().to_string());
                    }
                }
            }
        }
    }

    Ok(models)
}

